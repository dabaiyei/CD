def scene_guidance(source: str | dict, *, limit: int = 2) -> str:
    """Small reference cards, not a genre classifier or permission to invent actions."""
    if isinstance(source, dict):
        source = json.dumps(
            {
                key: source.get(key)
                for key in ("title", "scene_description", "action_description", "dialogue", "internal_shots")
                if source.get(key)
            },
            ensure_ascii=False,
        )
    cards = [text for _, pattern, text in SCENE_CARDS if re.search(pattern, source, re.I)][
        : max(0, min(limit, 2))
    ]
    if not cards:
        return ""
    return "\n【本场景镜头参考】仅在当前实际剧情适用时采用，否定/历史提及不是新增动作授权。" + "".join(cards)


def stage_guidance(stage: str) -> str:
    if stage == "project-assistant":
        return (
            "\n以下镜头语言仅在受托编写/修复分镜或视频提示词时使用，普通讨论和其它项目操作不扩写："
            + PLANNING_RULES
        )
    if stage in {"storyboard-generation", "storyboard-repair"}:
        return PLANNING_RULES
    if stage == "storyboard-review":
        return REVIEW_RULES
    if stage == "video-prompt-generation":
        return VIDEO_RULES
    if stage in {"script-generation", "script-repair"}:
        return (
            "\n【可视化叙事】每场明确视点、关键可见信息和情绪转折，为后续景别与运镜提供动机；"
            "保留原文指定镜头与时间轴。不把剧本写成摄影术语清单，具体运镜留给分镜与视频阶段。"
        )
    return ""
